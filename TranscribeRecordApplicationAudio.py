class AudioCapture(LogShellUser):
  "Handles audio recording via FFmpeg."
  def __init__(self, logShell: ScriptLogShell=ScriptLogShell()):
    super().__init__(logShell); self.process = None
  def startStereoRecord(self, inputSource: str=f"{Conf.sinkName}.monitor"):
    "Records dual-channel stereo (Left=Interviewer, Right=Candidate)."
    outputWav = self.logShell.outputAudioFile
    cmd = ["ffmpeg", "-n", "-thread_queue_size", "2048", "-f", "pulse", "-i", inputSource,
           "-ac", "2", "-ar", "16000", "-flush_packets", "1", outputWav,]
    self.logInfo(f"[AudioCapture] Starting dual-channel recording to {outputWav}...")
    self.process = self.shSpawn(cmd, stdin=subprocess.PIPE, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return self
  def stopRecording(self):
    "Stops the FFmpeg process gracefully."
    if self.isAlive():
      self.logInfo("[AudioCapture] Stopping recording...")
      self.process.send_signal(signal.SIGINT)
      try: self.process.wait(timeout=3)
      except subprocess.TimeoutExpired: self.process.kill()
      self.logInfo("[AudioCapture] Recording saved.")
    return self
  def isAlive(self) -> bool: return self.process is not None and self.process.poll() is None
  def enforceActive(self, inputSource: str=f"{Conf.sinkName}.monitor") -> bool:
    if not self.isAlive():
      self.logWarn("[CRITICAL] Recording process died! Attempting restart...")
      self.logShell.refreshOutputAudioFile()
      self.startStereoRecord(inputSource); return False
    return True
