class PulseAudioMixer(LogShellUser):
  """Manages PulseAudio virtual sink and loopbacks for call recording."""
  def __init__(self, sinkName: str=Conf.sinkName, logShell: ScriptLogShell=ScriptLogShell()):
    super().__init__(logShell); self.sinkName = sinkName; self.loadedModules = []
  # setup, device routes
  # main setup routines
  def createCallMixNullSinkAndLoopbacksByKeyword(self,
   microphoneDeviceNameKeyword: str=Conf.microphoneDeviceNameKeyword,
   speakerDeviceNameKeyword: str=Conf.speakerDeviceNameKeyword) -> "Self":
    "setup config"
    self.logInfo("[PulseAudio] Setting up virtual sink and loopbacks...")
    self.createNullSink(); self.routeMicLoopbackToCallMixByKeywordSearch(microphoneDeviceNameKeyword)
    self.routeAudioLoopbackToCallMixByKeywordSearch(speakerDeviceNameKeyword)
    self.logInfo("[PulseAudio] Setup complete. Use pavucontrol to see config'd playback/recording devices.")
    return self
  def createCallMixNullSinkAndLoopbacksForManualPavucontrolSetup(self) -> "Self":
    "setup defaults"
    self.logInfo("[PulseAudio] Setting up virtual sink and loopbacks...")
    self.createNullSink(); self.routeMicLoopbackToCallMixDefaults(); self.routeAudioLoopbackToCallMixDefaults()
    self.logInfo("[PulseAudio] Setup complete. Use pavucontrol to manual config playback/recording devices.")
    return self
  def enforceCallMixNullSinkByKeyword(self, microphoneDeviceNameKeyword: str,
   speakerDeviceNameKeyword: str) -> bool:
    if not self.sinkExists():
      self.logWarn("[WARNING] call_mix sink vanished. Re-creating routing...")
      self.createCallMixNullSinkAndLoopbacksByKeyword(microphoneDeviceNameKeyword,
       speakerDeviceNameKeyword)
      return False
    return True
  # setup procedure step helpers
  def createNullSink(self) -> int:
    outputSinkId = self.pactlLoadModule(f'pactl load-module module-null-sink sink_name={self.sinkName} '
                                        f'sink_properties=device.description="{self.sinkName}"')
    self.loadedModules.append(outputSinkId); return outputSinkId
  def routeMicLoopbackToCallMixByKeywordSearch(self, micDeviceKeyword: str) -> int:
    micSource = self.pulseaudioFullSourceNameByKeywordSkipError("source", micDeviceKeyword)
    return self.routeMicLoopbackToCallMixByExactDeviceName(micSource)
  def routeMicLoopbackToCallMixDefaults(self) -> int: return self.routeMicLoopbackToCallMixByExactDeviceName()
  def routeMicLoopbackToCallMixByExactDeviceName(self, micSource: str="") -> int:
    micArg = f" source={micSource}" if micSource else ""
    outputLoopbackId = self.pactlLoadModule(f"pactl load-module module-loopback{micArg} sink={self.sinkName}")
    self.loadedModules.append(outputLoopbackId); return outputLoopbackId
  def routeAudioLoopbackToCallMixByKeywordSearch(self, speakerDeviceKeyword: str) -> int:
    speakerSink = self.pulseaudioFullSourceNameByKeywordSkipError("sink", speakerDeviceKeyword)
    return self.routeAudioLoopbackToCallMixByExactDeviceName(speakerSink)
  def routeAudioLoopbackToCallMixDefaults(self) -> int:
    return self.routeAudioLoopbackToCallMixByExactDeviceName()
  def routeAudioLoopbackToCallMixByExactDeviceName(self, speakerSink: str="") -> int:
    speakerArg = f" sink={speakerSink}" if speakerSink else ""
    outputLoopbackId = self.pactlLoadModule(
     f"pactl load-module module-loopback source={self.sinkName}.monitor{speakerArg}")
    self.loadedModules.append(outputLoopbackId); return outputLoopbackId
  # cleanup
  def unloadPulseaudioModulesCreatedBySession(self) -> "Self":
    "cleanup"
    self.logInfo("[PulseAudio] Unloading PulseAudio modules..."); remove = set()
    for mod_id in reversed(self.loadedModules):
      try: self.shRun(f"pactl unload-module {mod_id}"); remove.add(mod_id)
      except Exception as e: self.logInfo(f"[PulseAudio] Failed unloading module {mod_id}: {e}")
    self.loadedModules = [x for x in self.loadedModules if x not in remove]; return self
  # setup, app routes
  def routeAppPlaybackToCallMix(self, appKeywords: Sequence[str] | str = ["chrome"]) -> list[str]:
    "Finds running application playback stream (e.g., Chrome) and moves playback to sink."
    targetSinkIndex = self.sinkIndexOfName(self.sinkName)
    if missingNullSink := targetSinkIndex is None:
      self.logWarn(f"[PulseAudio] Warning: Sink '{self.sinkName}' does not exist.")
      return []
    def movePlaybackStream(inputStream: dict, appTitle: str) -> None:
      inputStreamId = inputStream["index"]; currentSinkIndex = inputStream.get("sink")
      if unattached := currentSinkIndex != targetSinkIndex and str(currentSinkIndex) != self.sinkName:
        self.logInfo(f"[PulseAudio] Moving playback of {appTitle} (ID {inputStreamId}) -> {self.sinkName}")
        self.shRun(f"pactl move-sink-input {inputStreamId} {self.sinkName}")
    return self.forEachMatchingPulseAudioStream(self.pulseaudioSinkInputDicts(), appKeywords,
      movePlaybackStream)
  def routeAppRecordingToCallMixMonitor(self, appKeywords: Sequence[str] | str = ["ffmpeg"]) -> list[str]:
    "Finds active recording stream (e.g., FFmpeg/whisper-stream) and points recording to sinkName.monitor."
    target = f"{self.sinkName}.monitor"
    def moveRecordingStream(outputStream: dict, appTitle: str) -> None:
      outputStreamId = outputStream["index"]
      self.logInfo(f"[PulseAudio] Moving recording stream {appTitle} (ID {outputStreamId}) -> {target}")
      self.shRun(f"pactl move-source-output {outputStreamId} {target}")
    return self.forEachMatchingPulseAudioStream(self.pulseaudioSourceOutputDicts(), appKeywords,
      moveRecordingStream)
  # pulse audio queries
  def pulseaudioFullSourceNameByKeywordSkipError(self, deviceType: str, searchKeyword: str) -> str:
    try: return self.pulseaudioFullSourceNameByKeyword(deviceType, searchKeyword)
    except Exception as e: self.logError(f"[PulseAudio] Device lookup error: {e}")
    return None
  def pulseaudioFullSourceNameByKeyword(self, deviceType: str, searchKeyword: str) -> str:
    devices = self.pulseaudioDeviceDicts(deviceType)
    for dev in devices:
      name = dev.get("name", "")
      desc = dev.get("description", "")
      if skipMonitors := deviceType == "source" and name.endswith(".monitor"): continue
      if (searchKeyword.lower() in name.lower() or searchKeyword.lower() in desc.lower()): return name
    return None
  def pulseaudioDeviceDicts(self, sinkOrSourceDeviceType: str="sink") -> list[dict]:
    arg = "sinks" if sinkOrSourceDeviceType == "sink" else "sources"
    deviceDetailsJson, _, _ = self.shRun(f"pactl -f json list {arg}"); return json.loads(deviceDetailsJson)
  def pulseaudioSinkInputDicts(self) -> list[dict]: return self.jsonSh(f"pactl -f json list sink-inputs")
  def pulseaudioSourceOutputDicts(self) -> list[dict]: return self.jsonSh(f"pactl -f json list source-outputs")
  def sinkExists(self) -> bool:
    sinksJsonText, _, _ = self.shRun('pactl -f json list sinks'); return self.sinkName in sinksJsonText
  def sinkIndexOfName(self, targetSinkName: str | None = None) -> int | None:
    "Finds integer index of a sink matching sink name (e.g. 'call_mix')."
    targetName = targetSinkName or self.sinkName
    for sink in self.pulseaudioDeviceDicts("sink"):
      if sink.get("name") == targetName: return sink.get("index")
    return None
  def forEachMatchingPulseAudioStream(self, streams: list[dict], appKeywords: Sequence[str] | str,
   onMatchAction: Callable[[int, str], None]) -> list[str]:
    "Over PulseAudio streams, match application keywords and executing onMatchAction callback on hits."
    matchedAppTitles: list[str] = []; normalizedKeywords = self.pluralStr(appKeywords)
    for stream in streams:
      binary, appTitle = self.extractPulseAudioAppMetadata(stream)
      if self.isAnyKeywordMatch(normalizedKeywords, [binary, appTitle]):
        onMatchAction(stream, appTitle); matchedAppTitles.append(appTitle)
    return matchedAppTitles
  def extractPulseAudioAppMetadata(self, streamDict: dict) -> tuple[str, str]:
    "Extracts normalized (lowercase) binary path and application title from stream properties dict."
    props = streamDict.get("properties", {}); binary = props.get("application.process.binary", "").lower()
    appTitle = props.get("application.name", "").lower(); return binary, appTitle
  def pactlLoadModule(self, cmd: str) -> int: return self.parsePactlId(self.shRun(cmd)[0])
  def parsePactlId(self, pactlStdout: str) -> int: return int(pactlStdout.strip()) 
  # helpers
  def jsonSh(self, cmd: str):
    jsonTextStdout, _, _ = self.shRun(cmd)
    return json.loads(jsonTextStdout) if jsonTextStdout else []
