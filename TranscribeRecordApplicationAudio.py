class SystemShell:
  """Production implementation of ShellProtocol with logger injection."""
  def __init__(self, logger: Optional[LoggerProtocol] = None): self.logger = logger or NullLogger()
  def _normalize_command(self, command: Sequence[str] | str) -> list[str]:
    """Ensures commands are converted safely to a list of arguments."""
    if isinstance(command, str): return shlex.split(command)
    return list(map(str, command))
  def run(self, command: Sequence[str] | str, check: bool = True, ignore_errors: bool = False) -> Tuple[str, str, int]:
    cmd_args = self._normalize_command(command); cmd_str = " ".join(cmd_args)
    self.logger.debug(f"Executing: '{cmd_str}'")
    process = subprocess.Popen(cmd_args, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    stdout, stderr = process.communicate(); return_code = process.poll() or 0
    if return_code != 0 and not ignore_errors:
      error_msg = f"Command failed ({return_code}): '{cmd_str}'"
      self.logger.error(f"{error_msg}\nStderr: {stderr.strip()}")
      if check: raise ShellExecutionError(cmd_str, return_code, stdout, stderr)
    return stdout, stderr, return_code
  def spawn(self, command: Sequence[str] | str, **kwargs) -> subprocess.Popen:
    cmd_args = self._normalize_command(command); cmd_str = " ".join(cmd_args)
    self.logger.debug(f"Spawning process: '{cmd_str}'"); return subprocess.Popen(cmd_args, **kwargs)
